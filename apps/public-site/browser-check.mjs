import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.PUBLIC_PREVIEW_URL || 'http://127.0.0.1:3120';
const output = fileURLToPath(new URL('./output/playwright/', import.meta.url));
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_BROWSER_PATH ? { executablePath: process.env.PLAYWRIGHT_BROWSER_PATH } : { channel: 'chrome' }) });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
const externalRequests = [], errors = [], requests = [], checks = [];
await context.route('**/*', route => {
  const request = route.request();
  requests.push({ method: request.method(), url: request.url() });
  if (new URL(request.url()).origin === base) return route.continue();
  externalRequests.push(request.url());
  return route.abort();
});
const page = await context.newPage();
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (['error', 'warning'].includes(message.type())) errors.push(message.text()); });
function pass(message) { checks.push(message); console.log('PASS', message); }
async function fit(width) {
  await page.setViewportSize({ width, height: width < 500 ? 844 : 1000 });
  const overflow = await page.evaluate(() => ({ fits: document.documentElement.scrollWidth <= innerWidth, width: document.documentElement.scrollWidth, height: document.documentElement.scrollHeight, elements: [...document.querySelectorAll('body *')].filter(node => (node.getBoundingClientRect().right > innerWidth + 1 || (node.scrollWidth > node.clientWidth && node.clientWidth > 0)) && getComputedStyle(node).position !== 'absolute').map(node => ({ tag: node.tagName, className: String(node.className), right: node.getBoundingClientRect().right, scroll: node.scrollWidth, client: node.clientWidth })).slice(0, 24) }));
  if (!overflow.fits) await page.screenshot({ path: `${output}/overflow-${width}.png` });
  assert.equal(overflow.fits, true, `No horizontal page overflow at ${width}px: ${JSON.stringify(overflow)}`);
}
try {
  const response = await page.goto(base);
  await page.waitForLoadState('networkidle');
  assert.equal(response.status(), 200);
  assert.equal(await page.getByRole('heading', { level: 1 }).count(), 1);
  assert.equal(await page.locator('form,input[type=email],input[type=password]').count(), 0);
  assert.equal((await response.headerValue('x-robots-tag')), 'noindex, nofollow');
  await page.screenshot({ path: `${output}/desktop-1440.png`, fullPage: true });
  await page.screenshot({ path: `${output}/desktop-hero-1440.png` });
  pass('Built public preview renders with one H1, no signup form, and noindex headers');
  for (const width of [320, 390, 768, 1024, 1440]) await fit(width);
  pass('No horizontal page overflow at 320, 390, 768, 1024, and 1440 pixels');
  await page.getByLabel('Choose an example age range').selectOption('13–15');
  await page.getByRole('button', { name: /02 Community/ }).click();
  assert.match(await page.getByRole('status').innerText(), /full 13–15 range includes an age below/);
  await page.getByLabel('Use a narrower 14–15 example').check();
  assert.match(await page.getByRole('status').innerText(), /guardian is required/);
  await page.getByLabel('Choose an example age range').selectOption('18+');
  assert.match(await page.getByRole('status').innerText(), /guardian is required/);
  pass('Full age range fails closed; explicit narrowing changes comparison; adult selection does not waive guardian condition');
  const details = page.getByRole('button', { name: 'See example details' });
  await details.focus(); await page.keyboard.press('Enter');
  await page.getByRole('dialog').waitFor();
  assert.match(await page.getByRole('dialog').innerText(), /Fictional example/i);
  assert.match(await page.getByRole('dialog').innerText(), /cannot be booked/);
  await page.screenshot({ path: `${output}/example-details-1440.png` });
  await page.keyboard.press('Escape');
  assert.equal(await details.evaluate(node => document.activeElement === node), true);
  pass('Keyboard opens native modal, Escape dismisses, focus returns, and booking boundary is visible');
  await page.getByRole('button', { name: /03 Education/ }).click();
  assert.match(await page.getByRole('heading', { level: 3, name: 'Remote reading preparation' }).innerText(), /Remote reading/);
  await page.getByRole('button', { name: /01 Environment/ }).click();
  await page.getByLabel('Choose an example age range').selectOption('16–17');
  assert.equal(await page.locator('.shimmer-spin').evaluate(node => getComputedStyle(node).animationName), 'none');
  pass('All activity selectors work and reduced motion disables Magic UI animation');
  await page.locator('summary').filter({ hasText: 'Can I join an opportunity from this page?' }).click();
  assert.equal(await page.locator('details[open]').count(), 1);
  await page.locator('summary').filter({ hasText: 'Can I join an opportunity from this page?' }).click();
  const brokenAnchors = await page.locator('a[href^="#"]').evaluateAll(links => links.map(a => a.getAttribute('href')).filter(href => !document.getElementById(href.slice(1))));
  assert.deepEqual(brokenAnchors, []);
  pass('FAQ disclosure works and every navigation/CTA anchor resolves');
  await fit(390); await page.goto(base); await page.waitForLoadState('networkidle');
  await page.screenshot({ path: `${output}/mobile-390.png`, fullPage: true });
  await page.screenshot({ path: `${output}/mobile-hero-390.png` });
  await page.locator('#preview').scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${output}/mobile-preview-390.png` });
  await fit(320); await page.goto(base); await page.waitForLoadState('networkidle');
  await page.screenshot({ path: `${output}/mobile-320.png`, fullPage: true });
  await fit(768); await page.goto(base); await page.waitForLoadState('networkidle');
  await page.screenshot({ path: `${output}/tablet-768.png`, fullPage: true });
  assert.deepEqual(externalRequests, []);
  assert.deepEqual(requests.filter(request => request.method !== 'GET'), []);
  assert.deepEqual(errors, []);
  pass('Actual production browser session has no external requests, mutations, console warnings, or page errors');
  await writeFile(`${output}/verification.json`, JSON.stringify({ verifiedAt: new Date().toISOString(), base, checks, externalRequests, errors, requestCount: requests.length }, null, 2));
} finally { await context.close(); await browser.close(); }
